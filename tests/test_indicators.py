def ours():
    d, m, b = I.adx(H, L, C, 14), I.macd(C), I.bollinger(C, 20, 2.0)
    return {
        "ema20": I.ema(C, 20), "rsi14": I.rsi(C, 14), "atr14": I.atr(H, L, C, 14), "adx14": d.adx,
        "pdi14": d.plus_di, "mdi14": d.minus_di, "macd": m.macd, "macd_signal": m.macd_signal, "bb_upper": b.bb_upper,
    }


@pytest.mark.parametrize("name", list(EXPECTED))
def test_matches_talib(name):
    got = ours()[name].to_numpy()
    assert np.allclose([got[i] for i in IDX], EXPECTED[name], atol=1e-8, equal_nan=True), name


def test_warmup_lengths_match_talib():
    o = ours()
    first = {k: int(np.flatnonzero(~np.isnan(v.to_numpy()))[0]) for k, v in o.items()}
    assert first == {"ema20": 19, "rsi14": 14, "atr14": 14, "adx14": 27, "pdi14": 14, "mdi14": 14, "macd": 33, "macd_signal": 33, "bb_upper": 19}


