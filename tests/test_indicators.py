def test_no_lookahead_values_do_not_change_when_future_bars_are_added():
    full = ours()
    C2, H2, L2 = C.iloc[:80], H.iloc[:80], L.iloc[:80]
    d = I.adx(H2, L2, C2, 14)
    for name, part in {"ema20": I.ema(C2, 20), "rsi14": I.rsi(C2, 14), "atr14": I.atr(H2, L2, C2, 14), "adx14": d.adx, "macd": I.macd(C2).macd}.items():
        assert np.allclose(part.to_numpy()[30:], full[name].to_numpy()[30:80], equal_nan=True), name


def test_donchian_excludes_current_bar_and_pct_rank():
    h = pd.Series([1, 2, 3, 10, 4], dtype=float)
    dc = I.donchian(h, h, 3)
    assert dc.dc_high.tolist()[3:] == [3.0, 10.0]
    r = I.pct_rank(pd.Series([1, 2, 3, 4, 0], dtype=float), 4)
    assert r.iloc[3] == 1.0 and r.iloc[4] == 0.25
